ALTER TABLE integration_outbox
    ADD COLUMN enqueue_sequence bigint GENERATED BY DEFAULT AS IDENTITY;

WITH ordered AS (
    SELECT id, row_number() OVER (
        ORDER BY created_at,
            regexp_replace(operation_key, ':page:[0-9]+$', ''),
            CASE WHEN operation_key ~ ':page:[0-9]+$'
                THEN substring(operation_key FROM ':page:([0-9]+)$')::bigint + 1
                ELSE 0
            END,
            operation_key,
            id
    ) AS value
    FROM integration_outbox
)
UPDATE integration_outbox AS item
SET enqueue_sequence = ordered.value
FROM ordered
WHERE item.id = ordered.id;

SELECT setval(
    pg_get_serial_sequence('integration_outbox', 'enqueue_sequence'),
    COALESCE(max(enqueue_sequence), 1),
    count(*) > 0
)
FROM integration_outbox;

CREATE INDEX integration_outbox_dispatch_order
    ON integration_outbox(integration, available_at, created_at, enqueue_sequence)
    WHERE status IN ('pending', 'retrying', 'applying');

UPDATE discord_conversations
SET configuration_deadline = NULL
WHERE configuration_status IN ('awaiting', 'editing')
  AND configuration_deadline IS NOT NULL;
